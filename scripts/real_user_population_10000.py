def _lower_first(text: str) -> str:
    return text[:1].lower() + text[1:] if text else text


def _strip_terminal(text: str) -> str:
    return text.rstrip().rstrip("?!.")


def _style_prompt(prompt: str, style: str, *, base: UserScenario) -> str:
    text = str(prompt or "").strip()
    if style == "exact":
        return text
    if style == "polite":
        if base.category == "instant" and re.match(r"^(?:привет|здравств|добро)", text, re.I):
            return text
        return "Подскажи, пожалуйста, " + _lower_first(text)
    if style == "mobile":
        return " ".join(_strip_terminal(text).lower().split())
    if style == "colloquial":
        value = text.replace("сейчас", "щас").replace("Сейчас", "Щас")
        value = value.replace("пожалуйста", "плиз")
        return "слушай, " + _lower_first(_strip_terminal(value))
    if style == "noisy":
        value = _strip_terminal(text)
        value = re.sub(r"\s+", "  ", value, count=1)
        return value + " 🙏"
    raise ValueError(style)


def build_population() -> tuple[SyntheticSession, ...]:
    rows: list[SyntheticSession] = []
    serial = 0
    for base in SCENARIOS:
        for persona in PERSONAS:
            persona_prompt = _PERSONA_PROMPTS.get(persona.id, {}).get(base.id, base.prompt)
            for style in STYLES:
                serial += 1
                rows.append(SyntheticSession(
                    id=f"S{serial:05d}", base_id=base.id,
                    persona=persona.id, persona_label=persona.label, segment=persona.segment, style=style,
                    prompt=_style_prompt(persona_prompt, style, base=base),
                    expected_path=base.expected_path, category=base.category,
                    min_chars=base.min_chars, max_chars=base.max_chars, must_include=base.must_include,
                    expect_web=base.expect_web, max_ttft_ms=base.max_ttft_ms, max_total_ms=base.max_total_ms,
                ))
    result = tuple(rows)
    assert len(result) == 10_000
    assert len({row.id for row in result}) == 10_000
    return result


POPULATION = build_population()


