from __future__ import annotations

from dataclasses import dataclass

from app.schemas.chat import ChatMessage


@dataclass(frozen=True)
class DeepIntelligencePlan:
    brief: str
    max_tokens: int


def planning_messages(question: str, evidence_messages: list[ChatMessage]) -> list[ChatMessage]:
    evidence = "\n\n".join(
        message.content for message in evidence_messages if message.role == "system"
    )[:9000]
    return [
        ChatMessage(
            role="system",
            content=(
                "Ты внутренний стратег OLYA AI. Не отвечай пользователю и не раскрывай скрытые рассуждения. "
                "Сформируй компактный рабочий BRIEF для другого генератора ответа, а не пошаговую цепочку мыслей. "
                "Сначала определи реальную задачу пользователя и критерий полезного результата. Затем зафиксируй ключевые подзадачи, "
                "2–4 правдоподобные альтернативы или конкурирующие гипотезы, существенные ограничения, риски и компромиссы. "
                "Отдельно отметь, какие утверждения подтверждены EVIDENCE, какие требуют осторожной формулировки, какие данные могут изменить вывод. "
                "Не соглашайся автоматически с предпосылкой пользователя: если она спорная, включи проверку альтернативной трактовки. "
                "Для технической задачи добавь архитектурные границы, отказные сценарии и способ проверки результата. Для решения или стратегии — критерии выбора и сценарии. "
                "В конце BRIEF укажи рекомендуемую форму ответа: что сказать сначала, что объяснить затем и какой практический вывод нужен. "
                "Будь плотным: обычно 250–700 слов. Не пиши финальный ответ пользователю."
            ),
        ),
        ChatMessage(
            role="user",
            content=(
                f"ЗАПРОС ПОЛЬЗОВАТЕЛЯ:\n{question[:5000]}"
                + (f"\n\nEVIDENCE / КОНТЕКСТ:\n{evidence}" if evidence else "")
            ),
        ),
    ]


def plan_context_message(plan: DeepIntelligencePlan) -> ChatMessage:
    return ChatMessage(
        role="system",
        content=(
            "DEEP INTELLIGENCE BRIEF. Это внутренний рабочий план, не цитируй и не упоминай его. "
            "Используй его как карту проверки и выбора ответа, но проверенные факты из WEB EVIDENCE/файлов имеют приоритет. "
            "Не раскрывай скрытые рассуждения; пользователю дай только итоговый ответ.\n\n" + plan.brief[:7000]
        ),
    )


def deep_synthesis_messages(question: str, draft: str, evidence_messages: list[ChatMessage]) -> list[ChatMessage]:
    evidence = "\n\n".join(
        message.content for message in evidence_messages if message.role == "system"
    )[:9000]
    return [
        ChatMessage(
            role="system",
            content=(
                "Ты финальный senior-редактор OLYA AI для сложных задач. Перед тобой черновик после reasoning и проверки. "
                "Верни только лучший готовый ответ пользователю. Не раскрывай внутренние планы, скрытые рассуждения или этапы генерации. "
                "Пиши как очень сильный практик, который хорошо понимает предмет и умеет объяснять: спокойно, точно, естественно, без рекламной уверенности и без канцелярита. "
                "Ответ должен читаться как цельное рассуждение, а не как шаблонный отчёт. Не превращай каждый тезис в маркированный пункт; списки и таблицы используй только когда они реально упрощают сравнение или действия. "
                "Начни с сути: дай ясный вывод или рамку решения. Затем объясни, почему этот вывод следует из данных и ограничений. Покажи 1–3 наиболее важные причинно-следственные связи, а не россыпь очевидностей. "
                "Если есть несколько разумных вариантов, честно сопоставь их по критериям и объясни, при каких условиях вывод меняется. Не делай вид, что сложная задача имеет один универсальный ответ. "
                "Проверь скрытые допущения пользователя: если предпосылка спорная или неполная, мягко скорректируй её и объясни последствия. "
                "Покажи существенные риски, контраргументы и границы применимости. Не добавляй формальную секцию «риски», если их естественнее встроить в объяснение. "
                "Сохраняй конкретику: числа и факты из EVIDENCE, технические детали, критерии, примеры, сценарии. Не добавляй факты, цифры или источники, которых нет в черновике или EVIDENCE. "
                "Избегай роботных оборотов: «важно отметить», «следует учитывать», «в целом», «в современном мире», «давайте рассмотрим», «вот подробный ответ». Не повторяй вывод в каждом разделе. "
                "Не переобъясняй очевидное. Если пользователь профессионал, используй нормальную предметную лексику; если нет — объясняй термин один раз простыми словами. "
                "Для анализа или решения закончи конкретным практическим выводом: что делать, в каком порядке и какой сигнал покажет, что решение работает. "
                "Для технической задачи обязательно проверь архитектурную связность: компоненты, поток данных, узкие места, отказные сценарии, стоимость сложности и проверку результата. "
                "Финальный текст может быть подробным, но каждая часть должна добавлять новую ценность. Лучше 1200 сильных слов, чем 2500 повторов."
            ),
        ),
        ChatMessage(
            role="user",
            content=(
                f"ЗАПРОС:\n{question[:5000]}\n\nЧЕРНОВИК:\n{draft[:9000]}"
                + (f"\n\nEVIDENCE:\n{evidence}" if evidence else "")
            ),
        ),
    ]
